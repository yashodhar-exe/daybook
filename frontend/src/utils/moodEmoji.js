export function getMoodEmoji(mood) {
  if (!mood) return null;
  const trimmed = String(mood).trim();
  if (LEGACY_MOOD_MAP[trimmed]) {
    return LEGACY_MOOD_MAP[trimmed];
  }
  return trimmed;
}

export function getMoodLabel(moodOrEmoji) {
  if (!moodOrEmoji) return "";
  const trimmed = String(moodOrEmoji).trim();
  if (REVERSE_LEGACY_MAP[trimmed]) {
    return REVERSE_LEGACY_MAP[trimmed];
  }
  if (LEGACY_MOOD_MAP[trimmed]) {
    return trimmed;
  }
  if (EMOJI_TO_NAME[trimmed]) {
    return EMOJI_TO_NAME[trimmed]
      .split(" ")
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
      .join(" ");
  }
  return trimmed;
}

export function matchesMoodFilter(entryMood, selectedFilter) {
  if (!selectedFilter || selectedFilter === "All") return true;
  if (!entryMood) return false;

  const entryEmoji = getMoodEmoji(entryMood);
  const filterEmoji = getMoodEmoji(selectedFilter);

  return (
    entryEmoji === filterEmoji ||
    String(entryMood).toLowerCase() === String(selectedFilter).toLowerCase()
  );
}
